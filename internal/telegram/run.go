package telegram

import (
	"context"
	"fmt"
	"io"
	"net/http"

	tgbotapi "github.com/go-telegram-bot-api/telegram-bot-api/v5"
	"github.com/rs/zerolog/log"
)

// apiSender adapts *tgbotapi.BotAPI to the Sender interface used by Bot.
type apiSender struct {
	api *tgbotapi.BotAPI
}

func (s *apiSender) SendMessage(chatID int64, text string) error {
	_, err := s.api.Send(tgbotapi.NewMessage(chatID, text))
	return err
}

func (s *apiSender) DownloadPhoto(fileID string) ([]byte, error) {
	return s.downloadFile(fileID)
}

func (s *apiSender) DownloadDocument(fileID string) ([]byte, error) {
	return s.downloadFile(fileID)
}

func (s *apiSender) downloadFile(fileID string) ([]byte, error) {
	url, err := s.api.GetFileDirectURL(fileID)
	if err != nil {
		return nil, fmt.Errorf("get file url: %w", err)
	}

	resp, err := http.Get(url) //nolint:gosec // URL is generated by the Telegram API itself.
	if err != nil {
		return nil, fmt.Errorf("download file: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download file: unexpected status %d", resp.StatusCode)
	}

	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("read file body: %w", err)
	}
	return data, nil
}

func (s *apiSender) SendDocument(chatID int64, filename string, data []byte, caption string) error {
	file := tgbotapi.FileBytes{Name: filename, Bytes: data}
	msg := tgbotapi.NewDocument(chatID, file)
	msg.Caption = caption
	_, err := s.api.Send(msg)
	return err
}

// Run connects to Telegram with the given bot token and blocks, feeding updates into bot until
// ctx is canceled.
func Run(ctx context.Context, token string, bot *Bot) error {
	api, err := tgbotapi.NewBotAPI(token)
	if err != nil {
		return fmt.Errorf("connect to telegram: %w", err)
	}
	bot.Sender = &apiSender{api: api}

	log.Info().Str("username", api.Self.UserName).Msg("telegram bot connected")

	u := tgbotapi.NewUpdate(0)
	u.Timeout = 60
	updates := api.GetUpdatesChan(u)

	for {
		select {
		case <-ctx.Done():
			api.StopReceivingUpdates()
			return nil
		case update := <-updates:
			if u, ok := fromTG(update); ok {
				bot.HandleUpdate(ctx, u)
			}
		}
	}
}

// fromTG converts a Telegram update into a transport-neutral Update. It reports false for
// updates that carry no message.
func fromTG(update tgbotapi.Update) (Update, bool) {
	msg := update.Message
	if msg == nil {
		return Update{}, false
	}

	u := Update{ChatID: msg.Chat.ID, Text: msg.Text}
	if msg.From != nil {
		u.Username = msg.From.UserName
	}
	if msg.IsCommand() {
		u.Command = msg.Command()
	}
	if msg.Document != nil {
		u.Document = &File{ID: msg.Document.FileID, Name: msg.Document.FileName, MIME: msg.Document.MimeType}
	}
	if len(msg.Photo) > 0 {
		largest := msg.Photo[len(msg.Photo)-1]
		u.Photo = &File{ID: largest.FileID, MIME: "image/jpeg"}
	}
	return u, true
}
